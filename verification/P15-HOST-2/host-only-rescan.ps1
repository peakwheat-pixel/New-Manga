$ErrorActionPreference = 'Stop'
$root = Resolve-Path (Join-Path $PSScriptRoot '..\..')
$surfaces = @(
    (Join-Path $root 'apps/desktop/src-tauri/src/main.rs'),
    (Join-Path $root 'apps/desktop/src-tauri/build.rs'),
    (Join-Path $root 'apps/desktop/src-tauri/capabilities/m2rc1-commands.json')
)
$surfaces += @(Get-ChildItem (Join-Path $root 'apps/desktop/src-tauri/gen/schemas') -Filter '*.json' -File | ForEach-Object FullName)
$surfaces += @(Get-ChildItem (Join-Path $root 'apps/desktop/src-tauri/permissions/autogenerated') -Filter '*.toml' -File | ForEach-Object FullName)
$hits = @(Select-String -Path $surfaces -Pattern 'BindProfileCredential|ClearProfileCredential')
if ($hits.Count) { $hits | ForEach-Object { $_.ToString() }; throw 'A Host→Core credential command is exposed on a WebView surface' }
$bridge = Get-Content -LiteralPath (Join-Path $root 'apps/desktop/src-tauri/src/library_bridge.rs') -Raw
foreach ($name in 'BindProfileCredential', 'ClearProfileCredential') {
    if (-not $bridge.Contains($name)) { throw "Private Host→Core route is missing: $name" }
}
if ($bridge.Contains('P15 credential channel is unavailable')) { throw 'The old fail-closed credential stub remains' }
"WebView surfaces scanned=$($surfaces.Count) (3 source/config + 4 generated schemas + $((Get-ChildItem (Join-Path $root 'apps/desktop/src-tauri/permissions/autogenerated') -Filter '*.toml' -File).Count) permission files)"
'Host-only route matches in WebView surfaces=0'
'Private library_bridge Host→Core route names=2 (BindProfileCredential, ClearProfileCredential)'
'Obsolete unavailable credential stub=0'
'Result=PASS'
