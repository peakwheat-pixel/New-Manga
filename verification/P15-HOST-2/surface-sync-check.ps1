$ErrorActionPreference = 'Stop'
$root = Resolve-Path (Join-Path $PSScriptRoot '..\..')
$mainPath = Join-Path $root 'apps/desktop/src-tauri/src/main.rs'
$buildPath = Join-Path $root 'apps/desktop/src-tauri/build.rs'
$capPath = Join-Path $root 'apps/desktop/src-tauri/capabilities/m2rc1-commands.json'
$main = Get-Content -LiteralPath $mainPath -Raw
$build = Get-Content -LiteralPath $buildPath -Raw
function Read-CommandArray([string]$Name) {
    $match = [regex]::Match($main, "(?s)pub const ${Name}:.*?=\s*&\[(.*?)\];")
    if (-not $match.Success) { throw "Missing command array: $Name" }
    return @([regex]::Matches($match.Groups[1].Value, '"([^"\r\n]+)"') | ForEach-Object { $_.Groups[1].Value })
}
$production = Read-CommandArray 'PRODUCTION_COMMANDS'
$p15 = Read-CommandArray 'P15_SETTINGS_PRODUCTION_ONLY_COMMANDS'
$probe = Read-CommandArray 'PROBE_ONLY_COMMANDS'
$ac1 = Read-CommandArray 'AC1_TEST_COMMANDS'
if ($production.Count -ne 49 -or $p15.Count -ne 19 -or $probe.Count -ne 4 -or $ac1.Count -ne 3) { throw "Unexpected main.rs counts: production=$($production.Count), P15=$($p15.Count), probe-only=$($probe.Count), AC1-only=$($ac1.Count)" }
if (-not ($p15 -contains 'credential_put' -and $p15 -contains 'credential_clear')) { throw 'P15 production-only list is missing a credential command' }
$handlers = [regex]::Matches($main, '(?s)generate_handler!\[(.*?)\]')
if ($handlers.Count -ne 3) { throw "Expected 3 generate_handler! surfaces, found $($handlers.Count)" }
$handlerCounts = @($handlers | ForEach-Object { @([regex]::Matches($_.Groups[1].Value, '(?m)^\s*([a-z][a-z0-9_]*),?\s*$')).Count })
if (($handlerCounts -join ',') -ne '7,6,49') { throw "Unexpected handler sizes: $($handlerCounts -join ',')" }
$productionHandler = $handlers[2].Groups[1].Value
$productionHandlerNames = @([regex]::Matches($productionHandler, '(?m)^\s*([a-z][a-z0-9_]*),?\s*$') | ForEach-Object { $_.Groups[1].Value })
if (($productionHandlerNames -join ',') -ne ($production -join ',')) { throw 'Production generate_handler! differs from PRODUCTION_COMMANDS' }
$buildList = [regex]::Match($build, '(?s)AppManifest::new\(\)\.commands\(&\[(.*?)\]\)')
if (-not $buildList.Success) { throw 'Missing build.rs AppManifest command list' }
$buildNames = @([regex]::Matches($buildList.Groups[1].Value, '"([^"\r\n]+)"') | ForEach-Object { $_.Groups[1].Value })
if ($buildNames.Count -ne 56 -or @($production + $probe + $ac1).Count -ne 56) { throw "Unexpected build/ACL count: build=$($buildNames.Count)" }
if (($buildNames | Sort-Object -Unique).Count -ne 56) { throw 'Duplicate command in build.rs manifest' }
$capability = Get-Content -LiteralPath $capPath -Raw | ConvertFrom-Json
$capCommandPermissions = @($capability.permissions | Where-Object { $_ -like 'allow-*' })
$capEvents = @($capability.permissions | Where-Object { $_ -like 'core:event:*' })
if ($capCommandPermissions.Count -ne 56 -or $capEvents.Count -ne 2 -or $capability.permissions.Count -ne 58) { throw 'Capability permissions count mismatch' }
$aclPath = Join-Path $root 'apps/desktop/src-tauri/gen/schemas/acl-manifests.json'
$acl = Get-Content -LiteralPath $aclPath -Raw | ConvertFrom-Json -AsHashtable
$aclPermissions = $acl['__app-acl__']['permissions']
$aclAllow = @($aclPermissions.Keys | Where-Object { $_ -like 'allow-*' })
$aclDeny = @($aclPermissions.Keys | Where-Object { $_ -like 'deny-*' })
if ($aclPermissions.Count -ne 112 -or $aclAllow.Count -ne 56 -or $aclDeny.Count -ne 56) { throw 'Generated ACL permission count mismatch' }
$permissionFiles = @(Get-ChildItem (Join-Path $root 'apps/desktop/src-tauri/permissions/autogenerated') -Filter '*.toml' -File)
if ($permissionFiles.Count -ne 56) { throw "Expected 56 autogenerated permission files, got $($permissionFiles.Count)" }
$schemaFiles = @('acl-manifests.json','capabilities.json','desktop-schema.json','windows-schema.json') | ForEach-Object { Join-Path $root "apps/desktop/src-tauri/gen/schemas/$_" }
foreach ($schema in $schemaFiles) {
    $text = Get-Content -LiteralPath $schema -Raw
    if (-not ($text.Contains('allow-credential-put') -and $text.Contains('allow-credential-clear'))) { throw "Generated schema missing credential permissions: $schema" }
}
$webSurfaces = @($mainPath, $buildPath, $capPath) + $schemaFiles + @($permissionFiles | ForEach-Object FullName)
foreach ($surface in $webSurfaces) {
    $text = Get-Content -LiteralPath $surface -Raw
    if ($text.Contains('BindProfileCredential') -or $text.Contains('ClearProfileCredential')) { throw "Host-only Core route leaked into a WebView surface: $surface" }
}
$hostOnly = [regex]::Match((Get-Content -LiteralPath (Join-Path $root 'apps/desktop/src-tauri/src/library_bridge.rs') -Raw), 'pub const P15_HOST_ONLY_COMMANDS: \[&str; 2\]\s*=\s*\[P15_BIND_PROFILE_CREDENTIAL, P15_CLEAR_PROFILE_CREDENTIAL\]')
if (-not $hostOnly.Success) { throw 'Host-only command pair missing from private Core bridge inventory' }
"PRODUCTION_COMMANDS=$($production.Count) (49 expected)"
"P15_SETTINGS_PRODUCTION_ONLY_COMMANDS=$($p15.Count)"
"generate_handler! sizes: probe=7, AC1=6, production=$($handlerCounts[2])"
"command_allowlist frozen assertions: probe=7; AC1=6 (unchanged Rust tests)"
"build.rs AppManifest commands=$($buildNames.Count) = production 49 + probe-only 4 + AC1-only 3"
"capability command permissions=$($capCommandPermissions.Count); event permissions=$($capEvents.Count); total=$($capability.permissions.Count)"
"generated __app-acl__ permissions=$($aclPermissions.Count) = allow $($aclAllow.Count) + deny $($aclDeny.Count)"
"autogenerated permission files=$($permissionFiles.Count) (54 existing + 2 credential)"
"generated schemas synchronized=$($schemaFiles.Count)/4; credential permissions present in all four"
"host-only rescan=PASS; Host→Core names absent from main/build/capability/generated ACL/schema/permission surfaces; private bridge pair=2"
