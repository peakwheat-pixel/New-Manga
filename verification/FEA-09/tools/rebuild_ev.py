"""I011: rebuild verification/FEA-09/EV.md as a zero-PENDING, unique-ID ledger.

The old per-file ledger is preserved verbatim under verification/FEA-09/history/.
The canonical ledger is derived from `git ls-files` so every row is tracked, has
a unique EV id, a worktree SHA-256 and the commit that introduced the file.

Synthetic component directories (cache-component/grant-component/
native-registry) are regenerated by tests on every run and are intentionally not
versioned; the ledger records that decision once instead of freezing throwaway
uuids.
"""

from __future__ import annotations

import hashlib
import re
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = next(
    parent for parent in Path(__file__).resolve().parents
    if (parent / ".git").exists()
)
EVIDENCE = "verification/FEA-09"
EV_PATH = ROOT / EVIDENCE / "EV.md"
OLD_EV = ROOT / EVIDENCE / "history" / "EV-2026-11-03.md"
SYNTHETIC = (
    f"{EVIDENCE}/cache-component/",
    f"{EVIDENCE}/grant-component/",
    f"{EVIDENCE}/native-registry/",
)


def git(*args: str) -> str:
    return subprocess.run(
        ["git", *args], cwd=ROOT, check=True, text=True,
        stdout=subprocess.PIPE, stderr=subprocess.PIPE,
    ).stdout.strip()


def tracked() -> list[str]:
    return [line for line in git("ls-files", EVIDENCE).splitlines() if line]


def classify(path: str) -> str:
    if path.endswith("EV.md"):
        return "LEDGER"
    if path.endswith("AC-MATRIX.md"):
        return "CANONICAL"
    if "/history/" in path:
        return "HISTORICAL"
    if "/ipc/" in path:
        return "IPC"
    if "/logs/" in path:
        return "LOG"
    if path.endswith(".md"):
        return "DOC"
    if path.endswith((".png", ".jpg", ".bin", ".ndjson")):
        return "FIXTURE"
    return "SUPPORTING"


def row(index: int, path: str) -> str:
    absolute = ROOT / path
    payload = absolute.read_bytes()
    digest = hashlib.sha256(payload).hexdigest()
    added = git("log", "--diff-filter=A", "--format=%H", "-1", "--", path) or "-"
    last = git("log", "--format=%H", "-1", "--", path) or "-"
    return (
        f"| EV-{index:03d} | `{path}` | {len(payload)} | `{digest}` | "
        f"`{added}` | `{last}` | {classify(path)} |"
    )


def archived_paths() -> list[tuple[str, str]]:
    if not OLD_EV.exists():
        return []
    found: list[tuple[str, str]] = []
    pattern = re.compile(r"`(verification/FEA-09/[^`]+)`")
    for line in OLD_EV.read_text(encoding="utf-8").splitlines():
        if not line.startswith("| EV-"):
            continue
        match = pattern.search(line)
        if not match:
            continue
        cells = [cell.strip() for cell in line.strip("|").split("|")]
        pin = cells[4] if len(cells) > 4 else "unknown"
        found.append((match.group(1), pin))
    return found


def main() -> int:
    files = [path for path in tracked() if path != f"{EVIDENCE}/EV.md"]
    files.sort()
    current = [path for path in files if not path.startswith(SYNTHETIC)]
    removed_synthetic = [path for path in files if path.startswith(SYNTHETIC)]
    current.sort()

    lines = [
        "# FEA-09 逐文件 EV（I011 收敛后；零 PENDING）",
        "",
        f"- 生成时间：{datetime.now(timezone.utc).isoformat(timespec='seconds')}",
        f"- HEAD：`{git('rev-parse', 'HEAD')}`",
        "- 口径：SHA-256 为工作树原始字节（不按 LF 归一）；`added_commit` = "
        "`git log --diff-filter=A`，`last_commit` = 最后一次修改该路径的提交。",
        "- 唯一 ID：EV-001…顺序编号，无重复、无 PENDING；旧台账原字节保留在 "
        "`verification/FEA-09/history/EV-2026-11-03.md`（HISTORICAL 行）。",
        "- 合成组件目录（`cache-component/`、`grant-component/`、`native-registry/`）"
        "由测试每次重新生成，已从版本控制移出并写入 `.gitignore`；不作为 canonical 证据。",
        "",
        "| EV | 仓库路径 | bytes | 工作树 SHA-256 | added_commit | last_commit | 类别 |",
        "|---|---|---:|---|---|---|---|",
    ]
    for index, path in enumerate(current, start=1):
        lines.append(row(index, path))

    lines += [
        "",
        "## 历史/已删除证据（不能用作当前交付证据）",
        "",
        "| 仓库路径 | 旧台账 pin | 处置 |",
        "|---|---|---|",
    ]
    tracked_set = set(tracked())
    missing: list[tuple[str, str]] = []
    seen: set[str] = set()
    for path, pin in archived_paths():
        if path in tracked_set or path in seen:
            continue
        seen.add(path)
        missing.append((path, pin))
    if not missing:
        lines.append("| — | — | 无：旧台账引用的所有路径仍被 git 跟踪 |")
    else:
        for path, pin in sorted(missing):
            lines.append(
                f"| `{path}` | `{pin}` | 仅存在于 git 历史（合成/临时证据，未纳入 canonical） |"
            )
    lines += [
        "",
        f"## 合成目录去跟踪记录",
        "",
        f"- 本次从索引移除的合成证据文件数：{len(removed_synthetic)}（测试生成，可重建）。",
        "- 决策：合成 UUID 路径不进入 canonical EV；保留测试源码与运行日志作为证据来源。",
        "",
        "## 未运行/限制",
        "",
        "- 本台账是文件级证据索引，不证明 AC 达成；AC 状态见 `AC-MATRIX.md`。",
        "- 真实 IPC/DPAPI/迁移/竞态等运行项以其日志与测试记录为准；未运行项不得据此宣称通过。",
    ]
    EV_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {EV_PATH} rows={len(current)} historical_missing={len(missing)} "
          f"synthetic_removed={len(removed_synthetic)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
