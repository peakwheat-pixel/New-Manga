"""Repository contract consumed by the library use cases.

Defined consumer-side (application layer) per hexagonal convention: use
cases depend on this protocol, persistence adapters implement it. The
SQLite adapter lands in a later infrastructure slice coordinated by Codex;
tests exercise the contract through in-memory fakes, including a
simulated restart (fresh service over the same repository data).
"""

from __future__ import annotations

from typing import Protocol

from domain.books.entities import Book, Chapter, Tag


class LibraryRepository(Protocol):
    """Persistence contract for books, chapters and tags."""

    # books
    def add_book(self, book: Book) -> None: ...
    def get_book(self, book_id: str) -> Book | None: ...
    def list_books(self) -> list[Book]: ...
    def update_book(self, book: Book) -> None: ...

    # chapters
    def add_chapter(self, chapter: Chapter) -> None: ...
    def get_chapter(self, chapter_id: str) -> Chapter | None: ...
    def list_chapters(self, book_id: str) -> list[Chapter]: ...
    def update_chapter(self, chapter: Chapter) -> None: ...

    # tags
    def add_tag(self, tag: Tag) -> None: ...
    def get_tag(self, tag_id: str) -> Tag | None: ...
    def find_tag_by_name(self, name: str) -> Tag | None: ...
    def list_tags(self) -> list[Tag]: ...
    def update_tag(self, tag: Tag) -> None: ...
    def delete_tag(self, tag_id: str) -> None: ...
    def add_book_tag(self, book_id: str, tag_id: str) -> None: ...
    def remove_book_tag(self, book_id: str, tag_id: str) -> None: ...
    def list_tags_of_book(self, book_id: str) -> list[Tag]: ...
