using Avalonia;
using Avalonia.Controls;
using Avalonia.Media;
using Avalonia.Styling;
using NewManga.DesignSystem;
using NewManga.ThemeEngine;
using DesignSystemResourceSource = NewManga.DesignSystem.Theming.DesignSystemResourceSource;
using DesignSystemThemeManager = NewManga.DesignSystem.Theming.DesignSystemThemeManager;
using IDesignSystemResourceSource = NewManga.DesignSystem.Theming.IDesignSystemResourceSource;

namespace NewManga.App.ViewModels.V2.ThemeStudio;

/// <summary>
/// Composes a scope-ready <c>Nm.*</c> token layer from a <see cref="ThemePackage"/> plus the independent
/// appearance knobs (THEME_STUDIO_SPEC §1 invariant 1: theme = personality, appearance/density = settings).
///
/// <para>
/// The personality layer comes from the Theme Engine's own <see cref="ThemePaletteComposer"/> (59 typed
/// keys: colours / fonts / font sizes / line heights / corners / motion) — this class never re-derives a
/// token value. The three appearance overlays are the design system's shipped dictionaries
/// (high-contrast, density, reduced-motion), merged on top in the frozen precedence order
/// (DESIGN_SYSTEM §2.3, §4).
/// </para>
///
/// <para>
/// Used for the surface's <em>scoped</em> palettes: theme cards, the preview simulation and the unsaved
/// editor draft. Applying a theme application-wide goes through the engine's
/// <see cref="ThemeService"/>/sink path, never through this class.
/// </para>
/// </summary>
public sealed class ThemeStudioPaletteBuilder
{
    private readonly IDesignSystemResourceSource _resources;
    private readonly Func<bool> _platformIsLight;
    private readonly Dictionary<string, ResourceDictionary?> _overlayCache = new(StringComparer.Ordinal);

    /// <summary>Creates a builder over the design-system resource source.</summary>
    /// <param name="resources">Design-system dictionary source (test seams substitute broken sources).</param>
    /// <param name="platformIsLight">Resolves <see cref="AppearanceMode.System"/>; defaults to the live Avalonia variant.</param>
    public ThemeStudioPaletteBuilder(IDesignSystemResourceSource? resources = null, Func<bool>? platformIsLight = null)
    {
        _resources = resources ?? DesignSystemResourceSource.Default;
        _platformIsLight = platformIsLight ?? DefaultPlatformIsLight;
    }

    /// <summary>Resolves the appearance of a request to a concrete palette variant.</summary>
    public PaletteVariant ResolveVariant(ThemeStudioPaletteRequest request) =>
        request.VariantOverride ?? ThemePaletteComposer.ResolveVariant(request.Appearance, _platformIsLight());

    /// <summary>Builds the scoped palette for one package + appearance request.</summary>
    public ThemeStudioPalette Build(ThemePackage package, ThemeStudioPaletteRequest request)
    {
        ArgumentNullException.ThrowIfNull(package);
        ArgumentNullException.ThrowIfNull(request);

        var variant = ResolveVariant(request);
        return new ThemeStudioPalette(package.Descriptor.Id, variant, BuildTokenLayer(package, request, variant));
    }

    private ResourceDictionary BuildTokenLayer(ThemePackage package, ThemeStudioPaletteRequest request, PaletteVariant variant)
    {
        var tokens = new ResourceDictionary();

        // 1) Theme personality: the engine owns every derived value (never re-implemented here).
        foreach (var pair in ThemePaletteComposer.Compose(package, variant))
        {
            tokens[pair.Key] = pair.Value;
        }

        // 2) "跟随系统强调色": V1 uses the application-level accent baseline for the active variant
        //    (no OS accent API is wired; see GAP-3).
        if (request.FollowSystemAccent)
        {
            OverlayAccentBaseline(tokens, variant);
        }

        // 3) High contrast is a full palette overlay generated by the design system.
        if (request.Contrast == ContrastMode.High)
        {
            OverlayHighContrast(tokens, variant);
        }

        // 4) Density (independent of theme; the design system owns both profiles).
        if (request.Density != Density.Comfortable)
        {
            OverlayFlat(tokens, request.Density == Density.Compact ? _resources.CompactDensity : _resources.SpaciousDensity);
        }

        // 5) Reduced motion wins over the theme's own durations.
        if (request.ReducedMotion)
        {
            OverlayFlat(tokens, _resources.ReducedMotion);
        }
        else
        {
            tokens[NmKeys.Motion.Enabled] = true;
        }

        return tokens;
    }

    /// <summary>Overrides the six accent keys with the design system's baseline accent (system accent proxy).</summary>
    private void OverlayAccentBaseline(ResourceDictionary tokens, PaletteVariant variant)
    {
        var source = variant == PaletteVariant.Light ? _resources.LightPalette : _resources.DarkPalette;
        if (!TryLoad(source, out var palette) || palette is null)
        {
            return;
        }

        foreach (var key in AccentKeys)
        {
            if (palette.TryGetResource(key, ThemeVariant.Default, out var value) && value is IBrush brush)
            {
                tokens[key] = brush;
            }
        }
    }

    /// <summary>
    /// Merges the theme-scoped high-contrast palette for one variant. The dictionary is only probed for
    /// the 35 frozen colour keys, so the design system stays the single source of the values.
    /// </summary>
    private void OverlayHighContrast(ResourceDictionary tokens, PaletteVariant variant)
    {
        if (!TryLoad(_resources.HighContrastPalette, out var overlay) || overlay is null)
        {
            return;
        }

        var themeVariant = variant == PaletteVariant.Light ? ThemeVariant.Light : ThemeVariant.Dark;
        if (overlay.ThemeDictionaries.TryGetValue(themeVariant, out var scoped) && scoped is IDictionary<object, object?> entries)
        {
            foreach (var key in ThemeTokenKeys.Colors)
            {
                if (entries.TryGetValue(key, out var value) && value is IBrush brush)
                {
                    tokens[key] = brush;
                }
            }

            return;
        }

        foreach (var key in ThemeTokenKeys.Colors)
        {
            if (overlay.TryGetResource(key, themeVariant, out var value) && value is IBrush brush)
            {
                tokens[key] = brush;
            }
        }
    }

    /// <summary>Merges a flat design-system overlay (density / reduced motion) into the token layer.</summary>
    private void OverlayFlat(ResourceDictionary tokens, Uri source)
    {
        if (!TryLoad(source, out var overlay) || overlay is null)
        {
            return;
        }

        foreach (var pair in (IDictionary<object, object?>)overlay)
        {
            if (pair.Key is string key)
            {
                tokens[key] = pair.Value;
            }
        }
    }

    private bool TryLoad(Uri source, out ResourceDictionary? dictionary)
    {
        if (_overlayCache.TryGetValue(source.AbsoluteUri, out dictionary))
        {
            return dictionary is not null;
        }

        DesignSystemThemeManager.TryLoad(source, out dictionary);
        _overlayCache[source.AbsoluteUri] = dictionary;
        return dictionary is not null;
    }

    private static bool DefaultPlatformIsLight()
    {
        var application = Application.Current;
        return application is null || application.ActualThemeVariant != ThemeVariant.Dark;
    }

    private static readonly string[] AccentKeys =
    [
        NmKeys.Color.Accent.Base,
        NmKeys.Color.Accent.Hover,
        NmKeys.Color.Accent.Active,
        NmKeys.Color.Accent.Muted,
        NmKeys.Color.Accent.On,
        NmKeys.Color.Accent.Ring,
    ];
}
