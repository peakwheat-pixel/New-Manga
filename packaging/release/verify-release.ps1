# RELEASE-VERIFY-1: verify release artifacts against packaging/release/SHA256SUMS.
#
# The manifest stores "<sha256>  <filename>" only, so this script must locate the real artifacts.
# Resolution order per file:
#   1. explicit -BaseZip / -ModelsZip / -SetupExe;
#   2. -ArtifactDir\<filename> (a release staging directory containing all three files);
#   3. the known task-env locations (AGPL-RELEASE-1 out for the two zips, NSIS-INSTALLER-1 out for setup.exe).
# Missing files and hash mismatches are reported per item and make the script exit 1.
#
# Usage:
#   pwsh -NoProfile -File packaging/release/verify-release.ps1
#   pwsh -NoProfile -File packaging/release/verify-release.ps1 -ArtifactDir <staging dir>
#   pwsh -NoProfile -File packaging/release/verify-release.ps1 -SetupExe <tampered copy>   # negative check
#   pwsh -NoProfile -File packaging/release/verify-release.ps1 -Quiet
[CmdletBinding()]
param(
    [string]$Manifest = '',
    [string]$ArtifactDir = '',
    [string]$BaseZip = '',
    [string]$ModelsZip = '',
    [string]$SetupExe = '',
    [switch]$Quiet
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

$releaseDir = $PSScriptRoot
$repoRoot = (Resolve-Path (Join-Path $releaseDir '..\..')).Path
$defaultBase = 'G:/CODEX/New Manga.workspace/task-envs/AGPL-RELEASE-1/out/NewManga-0.1.0-win-x64.zip'
$defaultModels = 'G:/CODEX/New Manga.workspace/task-envs/AGPL-RELEASE-1/out/NewManga-0.1.0-win-x64-models.zip'
$defaultSetup = 'G:/CODEX/New Manga.workspace/task-envs/NSIS-INSTALLER-1/out/NewManga-0.1.0-setup.exe'

if ([string]::IsNullOrWhiteSpace($Manifest)) {
    $Manifest = Join-Path $releaseDir 'SHA256SUMS'
} elseif (-not [System.IO.Path]::IsPathRooted($Manifest)) {
    $Manifest = Join-Path $repoRoot $Manifest
}
if (-not (Test-Path -LiteralPath $Manifest)) { throw "manifest not found: $Manifest" }

$artifactDirFull = if ([string]::IsNullOrWhiteSpace($ArtifactDir)) { '' } else { (Resolve-Path -LiteralPath $ArtifactDir).Path }

function Get-Sha256([string]$Path) {
    $stream = [System.IO.File]::OpenRead($Path)
    try {
        $sha = [System.Security.Cryptography.SHA256]::Create()
        try {
            return ([System.BitConverter]::ToString($sha.ComputeHash($stream))).Replace('-', '').ToLowerInvariant()
        } finally { $sha.Dispose() }
    } finally { $stream.Dispose() }
}

function Resolve-Role([string]$FileName) {
    if ($FileName -match '(?i)models\.zip$') { return 'models_zip' }
    if ($FileName -match '(?i)\.zip$') { return 'base_zip' }
    if ($FileName -match '(?i)\.exe$') { return 'setup_exe' }
    return 'unknown'
}

function Resolve-Artifact([string]$FileName, [string]$Role) {
    $explicit = switch ($Role) {
        'base_zip' { $BaseZip }
        'models_zip' { $ModelsZip }
        'setup_exe' { $SetupExe }
        default { '' }
    }
    if (-not [string]::IsNullOrWhiteSpace($explicit)) { return $explicit }
    if (-not [string]::IsNullOrWhiteSpace($artifactDirFull)) { return (Join-Path $artifactDirFull $FileName) }
    switch ($Role) {
        'base_zip' { return $defaultBase }
        'models_zip' { return $defaultModels }
        'setup_exe' { return $defaultSetup }
        default { return '' }
    }
}

# Parse manifest: "<sha256>  <filename>" (sha256sum also accepts " *<filename>").
$entries = New-Object System.Collections.Generic.List[object]
$lineNumber = 0
foreach ($line in [System.IO.File]::ReadAllLines($Manifest)) {
    $lineNumber++
    if ([string]::IsNullOrWhiteSpace($line) -or $line.TrimStart().StartsWith('#')) { continue }
    $match = [regex]::Match($line, '^([0-9a-fA-F]{64})[ \t]+\*?(.+?)[ \t]*$')
    if (-not $match.Success) { throw "invalid manifest line $lineNumber in ${Manifest}: $line" }
    $entries.Add([ordered]@{
        line = $lineNumber
        expected_sha256 = $match.Groups[1].Value.ToLowerInvariant()
        filename = $match.Groups[2].Value
        role = Resolve-Role $match.Groups[2].Value
    })
}
if ($entries.Count -eq 0) { throw "manifest has no entries: $Manifest" }

# Optional sidecar JSON (generated by generate-checksums.ps1) adds a byte-size cross-check.
$sidecarPath = "$Manifest.json"
$sidecarBytes = @{}
if (Test-Path -LiteralPath $sidecarPath) {
    $sidecar = Get-Content -LiteralPath $sidecarPath -Raw | ConvertFrom-Json
    foreach ($artifact in @($sidecar.artifacts)) { $sidecarBytes[[string]$artifact.filename] = [long]$artifact.bytes }
}

$failures = New-Object System.Collections.Generic.List[string]
$checked = 0
if (-not $Quiet) {
    Write-Host ("manifest: {0} ({1} entries)" -f $Manifest, $entries.Count)
}
foreach ($entry in $entries) {
    $checked++
    $path = Resolve-Artifact $entry.filename $entry.role
    if ([string]::IsNullOrWhiteSpace($path) -or -not (Test-Path -LiteralPath $path)) {
        $failures.Add("MISSING  $($entry.filename)  (looked for: $path)")
        Write-Host ("FAIL  {0}  MISSING (looked for: {1})" -f $entry.filename, $path)
        continue
    }
    $item = Get-Item -LiteralPath $path
    $actualSha = Get-Sha256 $item.FullName
    $ok = ($actualSha -eq $entry.expected_sha256)
    if ($ok -and $sidecarBytes.ContainsKey($entry.filename)) {
        if ($item.Length -ne $sidecarBytes[$entry.filename]) {
            $ok = $false
            $failures.Add("SIZE     $($entry.filename)  expected=$($sidecarBytes[$entry.filename]) actual=$($item.Length)")
            Write-Host ("FAIL  {0}  size mismatch expected={1} actual={2}" -f $entry.filename, $sidecarBytes[$entry.filename], $item.Length)
            continue
        }
    }
    if (-not $ok) {
        $failures.Add("HASH     $($entry.filename)  expected=$($entry.expected_sha256) actual=$actualSha")
        Write-Host ("FAIL  {0}  sha256 expected={1} actual={2}" -f $entry.filename, $entry.expected_sha256, $actualSha)
        continue
    }
    if (-not $Quiet) {
        Write-Host ("OK    {0}  {1}  ({2:N0} bytes)  {3}" -f $entry.filename, $actualSha, $item.Length, $item.FullName)
    }
}

$failedCount = $failures.Count
if ($failedCount -gt 0) {
    Write-Host ''
    foreach ($failure in $failures) { Write-Host $failure }
    Write-Host ("RELEASE VERIFY: FAIL ({0}/{1} entries failed)" -f $failedCount, $entries.Count)
    exit 1
}
Write-Host ("RELEASE VERIFY: PASS ({0}/{1} artifacts match SHA256SUMS)" -f $entries.Count, $entries.Count)
exit 0
